import { protocol } from 'electron'
import { createReadStream } from 'fs'
import { stat } from 'fs/promises'
import { extname, join } from 'path'
import { Readable } from 'stream'
import type { LibraryRepository } from '../library/repository'

/** asset://<kind>/<asset id>  where kind is thumb | sprite | preview | wave | original */
export const ASSET_SCHEME = 'asset'

const MIME: Record<string, string> = {
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.gif': 'image/gif',
  '.mp4': 'video/mp4',
  '.m4v': 'video/mp4',
  '.mov': 'video/quicktime',
  '.webm': 'video/webm',
  '.m4a': 'audio/mp4',
  '.mp3': 'audio/mpeg',
  '.wav': 'audio/wav',
  '.aac': 'audio/aac',
  '.flac': 'audio/flac',
  '.ogg': 'audio/ogg'
}

/** Must run before app "ready". */
export function registerAssetScheme(): void {
  protocol.registerSchemesAsPrivileged([
    {
      scheme: ASSET_SCHEME,
      privileges: { standard: true, secure: true, supportFetchAPI: true, stream: true }
    }
  ])
}

/** Parses "bytes=start-end" against a file size. Returns null for unsatisfiable ranges. */
export function parseRange(header: string | null, size: number): [number, number] | null {
  if (!header) return null
  const match = /^bytes=(\d*)-(\d*)$/.exec(header.trim())
  if (!match) return null
  let start = match[1] ? Number(match[1]) : NaN
  let end = match[2] ? Number(match[2]) : NaN
  if (Number.isNaN(start)) {
    if (Number.isNaN(end)) return null
    start = Math.max(0, size - end) // suffix range: last N bytes
    end = size - 1
  } else if (Number.isNaN(end) || end >= size) {
    end = size - 1
  }
  return start <= end && start < size ? [start, end] : null
}

async function serveFile(path: string, request: Request): Promise<Response> {
  const info = await stat(path)
  const type = MIME[extname(path).toLowerCase()] ?? 'application/octet-stream'
  const header = request.headers.get('range')
  const range = parseRange(header, info.size)
  const headers = { 'Content-Type': type, 'Accept-Ranges': 'bytes', 'Cache-Control': 'no-cache' }
  if (!range && header && /^bytes=(\d+-\d*|-\d+)$/.test(header.trim())) {
    // A well-formed range outside the file (it shrank, or a stale player position).
    return new Response(null, {
      status: 416,
      headers: { ...headers, 'Content-Range': `bytes */${info.size}` }
    })
  }
  if (range) {
    const [start, end] = range
    const body = Readable.toWeb(createReadStream(path, { start, end })) as ReadableStream
    return new Response(body, {
      status: 206,
      headers: {
        ...headers,
        'Content-Range': `bytes ${start}-${end}/${info.size}`,
        'Content-Length': String(end - start + 1)
      }
    })
  }
  const body = Readable.toWeb(createReadStream(path)) as ReadableStream
  return new Response(body, { headers: { ...headers, 'Content-Length': String(info.size) } })
}

/**
 * Serves generated media and playable originals to the renderer by asset ID only, so the
 * renderer never names a path. Generated files always come from the media cache folder.
 */
export function handleAssetProtocol(repo: LibraryRepository, mediaDir: string): void {
  protocol.handle(ASSET_SCHEME, async (request) => {
    try {
      const url = new URL(request.url)
      const kind = url.hostname
      const id = url.pathname.replace(/^\//, '')
      if (!/^[0-9a-f-]{36}$/.test(id)) return new Response('Bad request', { status: 400 })

      let path: string | null = null
      if (kind === 'original') {
        path = repo.assetPath(id)
      } else if (kind === 'thumb' || kind === 'sprite' || kind === 'preview' || kind === 'wave') {
        const file = repo.mediaFiles(id)?.[kind]
        // Cache file names are generated by us; reject anything that isn't a bare name.
        if (file && !/[\\/]/.test(file)) path = join(mediaDir, file)
      }
      if (!path) return new Response('Not found', { status: 404 })
      return await serveFile(path, request)
    } catch {
      return new Response('Not found', { status: 404 })
    }
  })
}
